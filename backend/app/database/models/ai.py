"""AI Threat Intelligence database entities with strict multi-tenant isolation.

Defines:
- AIMessageAnalysis: Deep contextual intelligence analysis per ingested message
- ExtractedIOCRecord: Validated indicators of compromise (IP, URL, Crypto, UPI, etc.)
- ThreatAnomalyRecord: Statistical anomaly detections with Gemini interpretation
- IntelligenceCorrelation: Cross-source threat correlations and campaign links
- AITokenUsageRecord: Token consumption and cost accounting per model/operation
- AIAlertRecord: High-severity actionable threat alerts generated from AI findings
"""

from datetime import datetime, timezone
from typing import List, Optional
import uuid

from sqlalchemy import (
    BigInteger,
    Boolean,
    CheckConstraint,
    DateTime,
    Float,
    ForeignKey,
    Integer,
    JSON,
    String,
    Text,
    UniqueConstraint,
    func,
)
from sqlalchemy.dialects.postgresql import UUID as PG_UUID
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.database.base import Base


class AIMessageAnalysis(Base):
    """
    Structured threat analysis generated by the Gemini AI and local NLP pipeline.
    Stored in 'threat.ai_message_analyses'.
    """

    __tablename__ = "ai_message_analyses"
    __table_args__ = (
        CheckConstraint(
            "severity IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL', 'INFO')",
            name="ck_ai_analysis_severity",
        ),
        UniqueConstraint("tenant_id", "message_id", name="uq_ai_analysis_tenant_message"),
        {"schema": "threat"},
    )

    analysis_id: Mapped[uuid.UUID] = mapped_column(
        PG_UUID(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
    )
    tenant_id: Mapped[uuid.UUID] = mapped_column(
        PG_UUID(as_uuid=True),
        ForeignKey("iam.tenant_organizations.tenant_id", ondelete="RESTRICT"),
        nullable=False,
        index=True,
    )
    message_id: Mapped[str] = mapped_column(
        String(128),
        nullable=False,
        index=True,
    )
    channel_id: Mapped[str] = mapped_column(
        String(128),
        nullable=False,
        index=True,
    )
    threat_detected: Mapped[bool] = mapped_column(
        Boolean,
        default=False,
        nullable=False,
    )
    threat_category: Mapped[str] = mapped_column(
        String(64),
        default="BENIGN",
        nullable=False,
        index=True,
    )
    secondary_categories: Mapped[list] = mapped_column(
        JSON,
        default=list,
        nullable=False,
    )
    threat_description: Mapped[str] = mapped_column(
        Text,
        default="",
        nullable=False,
    )
    severity: Mapped[str] = mapped_column(
        String(20),
        default="INFO",
        nullable=False,
        index=True,
    )
    confidence_score: Mapped[float] = mapped_column(
        Float,
        default=0.0,
        nullable=False,
    )
    calibrated_score: Mapped[float] = mapped_column(
        Float,
        default=0.0,
        nullable=False,
    )
    slang_interpretations: Mapped[list] = mapped_column(
        JSON,
        default=list,
        nullable=False,
    )
    coded_language_detected: Mapped[bool] = mapped_column(
        Boolean,
        default=False,
        nullable=False,
    )
    supporting_evidence: Mapped[list] = mapped_column(
        JSON,
        default=list,
        nullable=False,
    )
    explanation: Mapped[str] = mapped_column(
        Text,
        default="",
        nullable=False,
    )
    recommended_action: Mapped[str] = mapped_column(
        Text,
        default="MONITOR",
        nullable=False,
    )
    model_used: Mapped[str] = mapped_column(
        String(64),
        default="gemini-2.5-flash",
        nullable=False,
    )
    prompt_tokens: Mapped[int] = mapped_column(
        Integer,
        default=0,
        nullable=False,
    )
    completion_tokens: Mapped[int] = mapped_column(
        Integer,
        default=0,
        nullable=False,
    )
    latency_ms: Mapped[float] = mapped_column(
        Float,
        default=0.0,
        nullable=False,
    )
    is_reviewed: Mapped[bool] = mapped_column(
        Boolean,
        default=False,
        nullable=False,
    )
    review_decision: Mapped[Optional[str]] = mapped_column(
        String(32),
        nullable=True,
    )
    review_notes: Mapped[Optional[str]] = mapped_column(
        Text,
        nullable=True,
    )
    analyzed_at_utc: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        default=lambda: datetime.now(timezone.utc),
        nullable=False,
        index=True,
    )

    iocs: Mapped[List["ExtractedIOCRecord"]] = relationship(
        "ExtractedIOCRecord",
        back_populates="analysis",
        cascade="all, delete-orphan",
    )

    def __repr__(self) -> str:
        return f"<AIMessageAnalysis msg={self.message_id} cat={self.threat_category} sev={self.severity} conf={self.confidence_score}>"


class ExtractedIOCRecord(Base):
    """
    Extracted and validated Indicators of Compromise from analyzed messages.
    Stored in 'threat.extracted_iocs'.
    """

    __tablename__ = "extracted_iocs"
    __table_args__ = (
        UniqueConstraint("tenant_id", "message_id", "ioc_type", "normalized_value", name="uq_extracted_ioc_dedup"),
        {"schema": "threat"},
    )

    ioc_id: Mapped[uuid.UUID] = mapped_column(
        PG_UUID(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
    )
    tenant_id: Mapped[uuid.UUID] = mapped_column(
        PG_UUID(as_uuid=True),
        ForeignKey("iam.tenant_organizations.tenant_id", ondelete="RESTRICT"),
        nullable=False,
        index=True,
    )
    analysis_id: Mapped[Optional[uuid.UUID]] = mapped_column(
        PG_UUID(as_uuid=True),
        ForeignKey("threat.ai_message_analyses.analysis_id", ondelete="CASCADE"),
        nullable=True,
        index=True,
    )
    message_id: Mapped[str] = mapped_column(
        String(128),
        nullable=False,
        index=True,
    )
    channel_id: Mapped[str] = mapped_column(
        String(128),
        nullable=False,
        index=True,
    )
    ioc_type: Mapped[str] = mapped_column(
        String(32),
        nullable=False,
        index=True,
        comment="e.g. ipv4, url, domain, crypto_btc, crypto_eth, crypto_tron, upi_id, email, phone, hash_sha256",
    )
    raw_value: Mapped[str] = mapped_column(
        String(500),
        nullable=False,
    )
    normalized_value: Mapped[str] = mapped_column(
        String(500),
        nullable=False,
        index=True,
    )
    defanged_value: Mapped[str] = mapped_column(
        String(500),
        nullable=False,
    )
    is_validated: Mapped[bool] = mapped_column(
        Boolean,
        default=True,
        nullable=False,
    )
    is_malicious: Mapped[bool] = mapped_column(
        Boolean,
        default=False,
        nullable=False,
    )
    confidence: Mapped[float] = mapped_column(
        Float,
        default=1.0,
        nullable=False,
    )
    context_snippet: Mapped[Optional[str]] = mapped_column(
        Text,
        nullable=True,
    )
    extracted_at_utc: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        default=lambda: datetime.now(timezone.utc),
        nullable=False,
        index=True,
    )

    analysis: Mapped[Optional[AIMessageAnalysis]] = relationship(
        "AIMessageAnalysis",
        back_populates="iocs",
    )

    def __repr__(self) -> str:
        return f"<ExtractedIOC type={self.ioc_type} val={self.defanged_value} msg={self.message_id}>"


